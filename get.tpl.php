<h1>Bemutatkozás</h1>

<p>
Valaha egy kisebb településen társadalmi esemény volt, ha „a csapat” játszott. Ha nem is annyian, mint akkor, de ma is állandó látogatói vannak a futballmérkőzéseknek. A kor követelményeinek megfelelően minden bérlettulajdonost és jegyvásárlót azonosítanak, rögzítik a nézőtéren való megjelenésüket is.
Az alapok:
A focit két csapat játssza egymás ellen, 11-11 játékossal. Egy csapat 10 mezőnyjátékossal és egy kapussal lép pályára. A játékosok nem érhetnek sem kézzel, sem karral a labdához, kivétel ez alól a kapus. A játék célja gólt rúgni, azaz a labdát az ellenfél kapujába juttatni.
</p>
<img src="images/futball.jpg "style="float:left; margin-right: 5px";>
<p>
A játékidő:
A foci játékideje 90 perc, két félidőre osztva, tehát 2 x 45 perc. Közötte van egy szusszanásnyi, 15 perces szünet. Az úgynevezett csoportmeccsek még végződhetnek döntetlennel, de az egyenes „kieséses" szakaszban már tényleges győzelemig játszanak. Először 2 x 15 perc hosszabbítás, majd „tizenegyes" rúgások következnek. Ezért is fontos, hogy te is drukkolj a gólért, különben sosem lesz vége.
</p>
